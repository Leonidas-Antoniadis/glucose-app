    // MARK: FRAM over NFC

    func testRealFRAMDecodesWithLittleEndianChecksums() throws {
        let decrypted = try Libre2Crypto.decryptFRAM(uid: Self.exampleUID, patchInfo: Self.examplePatchInfo,
                                                     data: Self.exampleFRAM)
        XCTAssertEqual(Array(decrypted[0..<2]), [0x24, 0xFA], "header CRC 0xFA24 is stored low byte first")
        XCTAssertEqual(try LibreFRAM.state(decrypted: decrypted), .active)

        let fram = try LibreFRAM(decrypted: decrypted)
        XCTAssertEqual(fram.state, .active)
        XCTAssertEqual(fram.ageMinutes, 10320)
        XCTAssertEqual(fram.maxLifeMinutes, 20719)
        XCTAssertEqual(fram.trend.count, 16)
        XCTAssertEqual(fram.trend.first?.minuteIndex, 10320)
        XCTAssertEqual(fram.trend.prefix(4).map(\.raw), [1314, 1317, 1322, 1326])
        XCTAssertEqual(fram.trend.last?.minuteIndex, 10305)
        XCTAssertEqual(fram.trend.last?.raw, 1416)
        XCTAssertEqual(fram.trend.first?.rawTemperature, 6552)
        XCTAssertEqual(fram.trend.first?.hasError, false)
        XCTAssertEqual(fram.history.count, 32)
        XCTAssertEqual(fram.history.prefix(3).map(\.minuteIndex), [10305, 10290, 10275])
        XCTAssertEqual(fram.history.prefix(3).map(\.raw), [1406, 1438, 1276])
    }

    func testSecondRealFRAMDecodes() throws {
        let decrypted = try Libre2Crypto.decryptFRAM(uid: Self.example2UID, patchInfo: Self.example2PatchInfo,
                                                     data: Self.example2FRAM)
        let fram = try LibreFRAM(decrypted: decrypted)
        XCTAssertEqual(fram.state, .active)
        XCTAssertEqual(fram.ageMinutes, 3170)
        XCTAssertEqual(fram.maxLifeMinutes, 20759)
        XCTAssertEqual(fram.trend.first?.raw, 1347)
        XCTAssertEqual(fram.trend.first?.rawTemperature, 5816)
        XCTAssertEqual(fram.history.first?.minuteIndex, 3165)
        XCTAssertEqual(fram.history.first?.raw, 1368)
    }

    func testRealFRAMFromAnotherSensorIsRejected() throws {
        let decrypted = try Libre2Crypto.decryptFRAM(uid: Self.example2UID, patchInfo: Self.example2PatchInfo,
                                                     data: Self.exampleFRAM)
        XCTAssertThrowsError(try LibreFRAM(decrypted: decrypted))
    }

    func testCaptureSensorsAreSupportedLibre2EU() {
        XCTAssertEqual(LibreSensorType(patchInfo: Self.examplePatchInfo), .libre2EU)
        XCTAssertEqual(LibreSensorType(patchInfo: Self.example2PatchInfo), .libre2EU)
    }

    // MARK: Bluetooth

    func testRealBLEPacketDecodes() throws {
        let decrypted = try Libre2Crypto.decryptBLE(uid: Self.bleUID, packet: Self.blePacket)
        let packet = try LibreBLEPacket(decrypted: decrypted)
        XCTAssertEqual(packet.ageMinutes, 11509)
        XCTAssertEqual(packet.trend.map(\.minuteIndex), [11509, 11507, 11505, 11503, 11502, 11497, 11494])
        XCTAssertEqual(packet.trend.map(\.raw), [2542, 2534, 2513, 2497, 2470, 2461, 2452])
        XCTAssertEqual(packet.latest?.rawTemperature, 6336)
        // Only the newest history slot is filled in this capture.
        XCTAssertEqual(packet.history.map(\.minuteIndex), [11505])
        XCTAssertEqual(packet.history.map(\.raw), [2514])
    }

    // MARK: NFC commands and Bluetooth login, against the reference implementations

    func testEnableStreamingMatchesReference() throws {
        let parameters = try Libre2Crypto.enableStreamingParameters(uid: Self.exampleUID, patchInfo: Self.examplePatchInfo)
        XCTAssertEqual(parameters, [0x1E, 0x2A, 0x00, 0x00, 0x00, 0x83, 0x27, 0x51, 0x3A],
                       "sub-command, unlock code 42 (little-endian), then 4 derived bytes")
    }

    func testActivateMatchesReference() throws {
        XCTAssertEqual(try Libre2Crypto.activateParameters(uid: Self.exampleUID), [0x1B, 0x29, 0xC6, 0xA3, 0x9D])
    }

    func testUnlockPayloadMatchesReference() throws {
        let uid = Self.exampleUID, patch = Self.examplePatchInfo
        XCTAssertEqual(try Libre2Crypto.streamingUnlockPayload(uid: uid, patchInfo: patch, unlockCount: 1),
                       [0x2B, 0x00, 0x00, 0x00, 0xD3, 0x48, 0xC4, 0xEF, 0x9B, 0x00, 0xC2, 0x85])
        XCTAssertEqual(try Libre2Crypto.streamingUnlockPayload(uid: uid, patchInfo: patch, unlockCount: 2),
                       [0x2C, 0x00, 0x00, 0x00, 0x31, 0x97, 0x17, 0xBB, 0xF5, 0x5A, 0x31, 0xD4])
    }
